/* ── Evaluation history + export (localStorage-backed) ── */

import { PORTFOLIOS } from "@anantam/shared";
import type { Evaluation } from "@anantam/shared";

const KEY = "evalscore.history.v1";
const MAX_ENTRIES = 24;

export function loadHistory(): Evaluation[] {
  try {
    const raw = localStorage.getItem(KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as Evaluation[];
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveToHistory(evaluation: Evaluation): Evaluation[] {
  const history = [evaluation, ...loadHistory()].slice(0, MAX_ENTRIES);
  try {
    localStorage.setItem(KEY, JSON.stringify(history));
  } catch {
    // Storage full — drop oldest entries until it fits.
    let trimmed = history;
    while (trimmed.length > 1) {
      trimmed = trimmed.slice(0, -1);
      try {
        localStorage.setItem(KEY, JSON.stringify(trimmed));
        return trimmed;
      } catch {
        /* keep trimming */
      }
    }
  }
  return history;
}

export function removeFromHistory(id: string): Evaluation[] {
  const history = loadHistory().filter((e) => e.id !== id);
  localStorage.setItem(KEY, JSON.stringify(history));
  return history;
}

function download(filename: string, mime: string, content: string) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportJson(e: Evaluation) {
  download(
    `evalscore-${e.fileName.replace(/\.pdf$/i, "")}-${e.id.slice(0, 8)}.json`,
    "application/json",
    JSON.stringify(e, null, 2),
  );
}

export function exportMarkdown(e: Evaluation) {
  const spec = PORTFOLIOS[e.portfolioType];
  const pct = Math.round((e.totalScore / e.totalMax) * 100);
  const lines: string[] = [
    `# EvalScore Report — ${e.fileName}`,
    ``,
    `**${e.portfolioTitle}** · evaluated ${new Date(e.createdAt).toLocaleString()}`,
    ``,
    `## Overall: ${e.totalScore} / ${e.totalMax} (${pct}%)`,
    ``,
    `| Criterion | Score | Band | Confidence |`,
    `|---|---|---|---|`,
  ];
  for (const r of e.results) {
    const c = spec.criteria.find((c) => c.id === r.criterionId);
    lines.push(`| ${c?.name ?? r.criterionId} | ${r.score}/${c?.maxMarks ?? "?"} | ${r.band} | ${r.confidence} |`);
  }
  for (const r of e.results) {
    const c = spec.criteria.find((c) => c.id === r.criterionId);
    lines.push(
      ``,
      `## ${c?.name ?? r.criterionId} — ${r.score}/${c?.maxMarks ?? "?"}`,
      ``,
      r.reasoning,
      ``,
      `**Strengths**`,
      ...r.strengths.map((s) => `- ${s}`),
      ``,
      `**Weaknesses**`,
      ...r.weaknesses.map((s) => `- ${s}`),
      ``,
      `**Evidence found**`,
      ...r.evidenceFound.map((ev) => `- "${ev.quote}" (p.${ev.page})`),
      ``,
      `**Missing evidence**`,
      ...r.missingEvidence.map((s) => `- ${s}`),
      ``,
      `**How to improve**`,
      ...r.improvements.map((s) => `- ${s}`),
    );
  }
  lines.push(
    ``,
    `---`,
    `Generated by EvalScore · Anantam Engineering Platform`,
  );
  download(
    `evalscore-${e.fileName.replace(/\.pdf$/i, "")}-report.md`,
    "text/markdown",
    lines.join("\n"),
  );
}
