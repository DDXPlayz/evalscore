/** Split a portfolio's criteria into evaluation groups of `size`, keeping
 *  visual criteria together in the final group so page images are sent once. */
export function criterionGroups(type: PortfolioType, size = 3): string[][] {
  const all = PORTFOLIOS[type].criteria;
  const textual = all.filter((c) => !c.visual).map((c) => c.id);
  const visual = all.filter((c) => c.visual).map((c) => c.id);
  const groups: string[][] = [];
  for (let i = 0; i < textual.length; i += size) {
    groups.push(textual.slice(i, i + size));
  }
  if (visual.length > 0) groups.push(visual);
  return groups;
}
