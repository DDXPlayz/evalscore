/* ── Official STEM Racing 2026 judging scorecards, encoded as data ──
 *
 * One module, three portfolio rule packs. Both the client engine (deterministic
 * scanning, relevance routing) and the evaluation server (prompt construction)
 * read from this single source of truth.
 *
 * Where the official scorecard assigns a combined mark to a judging area
 * (Project Management and Enterprise), EvalScore sub-allocates it across the
 * area's criteria so every criterion carries an explicit weight. Sub-allocated
 * marks always sum exactly to the official area total.
 */

import type { Criterion, PortfolioSpec, PortfolioType, ScoreBand } from "./types";

/** Build 4 quartile bands for qualitative (Poor/Basic/Good/Excellent) scorecards. */
function qualBands(max: number, descs: [string, string, string, string]): ScoreBand[] {
  const q = max / 4;
  const labels = ["Poor", "Basic", "Good", "Excellent"];
  return descs.map((description, i) => ({
    min: i === 0 ? 0 : Math.floor(q * i) + 1,
    max: Math.floor(q * (i + 1)),
    label: labels[i],
    description,
  }));
}

/** Build the standard 0-5 / 6-10 / 11-15 / 16-20 engineering bands. */
function engBands(descs: [string, string, string, string]): ScoreBand[] {
  const ranges: [number, number][] = [
    [0, 5],
    [6, 10],
    [11, 15],
    [16, 20],
  ];
  const labels = ["Limited", "Basic", "Good", "Excellent"];
  return descs.map((description, i) => ({
    min: ranges[i][0],
    max: ranges[i][1],
    label: labels[i],
    description,
  }));
}

